const maxOAuthStateExpirySeconds = int64(15 * 60)

// minOAuthStateRandomChars is the minimum number of characters the state must carry beyond the
// predictable "<key>_<channelID>_<justConnect>" value, i.e. enough room for >=128 bits of encoded randomness.
const minOAuthStateRandomChars = 20

func predictableOAuthState(userID, channelID string, justConnect bool) string {
	return fmt.Sprintf("%s_%s_%t", getOAuthUserStateKey(userID), channelID, justConnect)
}

// testOAuthStateNonce has the shape of a nonce generated by StoreState (32 random bytes, hex encoded).
var testOAuthStateNonce = strings.Repeat("0123456789abcdef", 4)

func wellFormedOAuthState(userID, channelID string, justConnect bool) string {
	return predictableOAuthState(userID, channelID, justConnect) + "." + testOAuthStateNonce
}

func isUnpredictableOAuthState(state, userID, channelID string, justConnect bool) bool {
	predictable := predictableOAuthState(userID, channelID, justConnect)
	return state != predictable &&
		strings.Contains(state, userID) &&
		strings.Contains(state, channelID) &&
		len(state) >= len(predictable)+minOAuthStateRandomChars
}

// expectStoreStateWithExpiry registers the only KV write StoreState is allowed to perform: a write of an
// unpredictable state under the user's state key with a short expiry. Use together with api.Test(t) so a
// write without expiry fails the test instead of panicking.
func expectStoreStateWithExpiry(api *plugintest.API, userID, channelID string, justConnect bool) *mock.Call {
	return api.On("KVSetWithExpiry",
		getOAuthUserStateKey(userID),
		mock.MatchedBy(func(value []byte) bool {
			return isUnpredictableOAuthState(string(value), userID, channelID, justConnect)
		}),
		mock.MatchedBy(func(expiry int64) bool {
			return expiry > 0 && expiry <= maxOAuthStateExpirySeconds
		}),
	).Return(nil)
}

func TestStoreState(t *testing.T) {
	testCases := []struct {
		name           string
		userID         string
		channelID      string
		justConnect    bool
		returnError    *model.AppError
		expectError    bool
		expectedErrMsg string
	}{
		{
			name:           "Error occurred while storing state",
			userID:         "mockUserID1",
			channelID:      "mockChannelID1",
			returnError:    &model.AppError{Message: "error occurred while storing state"},
			expectError:    true,
			expectedErrMsg: "error occurred while storing state",
		},
		{
			name:        "Store state successful for connect",
			userID:      "mockUserID2",
			channelID:   "mockChannelID2",
			justConnect: true,
		},
		{
			name:        "Store state successful for start meeting",
			userID:      "mockUserID3",
			channelID:   "mockChannelID3",
			justConnect: false,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			mockAPI := &plugintest.API{}
			mockAPI.Test(t)
			p := SetupMockPlugin(mockAPI, nil, nil)

			var storedValue []byte
			var storedExpiry int64
			storedWithoutExpiry := false
			mockAPI.On("KVSetWithExpiry", getOAuthUserStateKey(tc.userID), mock.Anything, mock.Anything).
				Run(func(args mock.Arguments) {
					storedValue = args.Get(1).([]byte)
					storedExpiry = args.Get(2).(int64)
				}).
				Return(tc.returnError).Maybe()
			mockAPI.On("KVSet", getOAuthUserStateKey(tc.userID), mock.Anything).
				Run(func(args mock.Arguments) {
					storedWithoutExpiry = true
					storedValue = args.Get(1).([]byte)
				}).
				Return(tc.returnError).Maybe()

			state, err := p.StoreState(tc.userID, tc.channelID, tc.justConnect)
			assert.False(t, storedWithoutExpiry, "the state must not be stored without an expiry")

			if tc.expectError {
				require.Error(t, err)
				require.Equal(t, tc.expectedErrMsg, err.Error())
				require.Empty(t, state)
			} else {
				require.NoError(t, err)

				assert.Equal(t, state, string(storedValue), "the stored state must be the returned state")
				assert.Greater(t, storedExpiry, int64(0), "the state must be stored with an expiry")
				assert.LessOrEqual(t, storedExpiry, maxOAuthStateExpirySeconds, "the state must be short-lived")

				predictable := predictableOAuthState(tc.userID, tc.channelID, tc.justConnect)
				assert.NotEqual(t, predictable, state, "the state must not be derivable from the user and channel IDs")
				assert.GreaterOrEqual(t, len(state), len(predictable)+minOAuthStateRandomChars, "the state must carry a random component")

				key, userID, channelID, justConnect, parseErr := p.ParseState(state)
				require.NoError(t, parseErr)
				require.Equal(t, getOAuthUserStateKey(tc.userID), key)
				require.Equal(t, tc.userID, userID)
				require.Equal(t, tc.channelID, channelID)
				require.Equal(t, tc.justConnect, justConnect)
			}
			mockAPI.AssertExpectations(t)
		})
	}
}

func TestStoreStateIsUnpredictable(t *testing.T) {
	mockAPI := &plugintest.API{}
	mockAPI.Test(t)
	p := SetupMockPlugin(mockAPI, nil, nil)

	userID := "mockUserID"
	channelID := "mockChannelID"
	mockAPI.On("KVSetWithExpiry", getOAuthUserStateKey(userID), mock.Anything, mock.Anything).Return(nil).Maybe()
	mockAPI.On("KVSet", getOAuthUserStateKey(userID), mock.Anything).Return(nil).Maybe()

	first, err := p.StoreState(userID, channelID, true)
	require.NoError(t, err)
	second, err := p.StoreState(userID, channelID, true)
	require.NoError(t, err)

	require.NotEqual(t, first, second, "repeated calls with identical arguments must yield different states")
	require.NotEqual(t, predictableOAuthState(userID, channelID, true), first, "the state must not be derivable from the user and channel IDs")
	mockAPI.AssertExpectations(t)
}

func TestGetState(t *testing.T) {
	testCases := []struct {
		name           string
		key            string
		getStateValue  []byte
		getStateError  error
		expectedState  string
		expectError    bool
		expectedErrMsg string
	}{
		{
			name:           "Error occurred while getting stored state",
			key:            "mockKey",
			getStateValue:  []byte(""),
			getStateError:  &model.AppError{Message: "error occurred while getting stored state"},
			expectError:    true,
			expectedErrMsg: "error occurred while getting stored state",
		},
		{
			name:          "Valid state retrieved",
			key:           "mockKey",
			getStateValue: []byte("mockState"),
			expectedState: "mockState",
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			api := &plugintest.API{}
			p := SetupMockPlugin(api, nil, nil)

			api.On("KVGet", tc.key).Return(tc.getStateValue, tc.getStateError)

			state, err := p.GetState(tc.key)
			if tc.expectError {
				require.Error(t, err)
				require.Equal(t, tc.expectedState, state)
				require.Equal(t, tc.expectedErrMsg, err.Error())
			} else {
				require.NoError(t, err)
				require.Equal(t, tc.expectedState, state)
			}
			api.AssertExpectations(t)
		})
	}
}

