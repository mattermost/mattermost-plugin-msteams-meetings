func TestParseState(t *testing.T) {
	testCases := []struct {
		name                string
		state               string
		expectedKey         string
		expectedUserID      string
		expectedChannelID   string
		expectedJustConnect bool
		expectError         bool
		expectedErrMsg      string
	}{
		{
			name:           "State length mismatch",
			state:          "key1_userID1_channelID1",
			expectError:    true,
			expectedErrMsg: "status mismatch",
		},
		{
			name:           "Invalid state format",
			state:          "key1_userID1",
			expectError:    true,
			expectedErrMsg: "status mismatch",
		},
		{
			name:                "Parse state successful for connect",
			state:               wellFormedOAuthState("userID1", "channelID1", true),
			expectedKey:         getOAuthUserStateKey("userID1"),
			expectedUserID:      "userID1",
			expectedChannelID:   "channelID1",
			expectedJustConnect: true,
		},
		{
			name:                "Parse state successful for start meeting",
			state:               wellFormedOAuthState("userID1", "channelID1", false),
			expectedKey:         getOAuthUserStateKey("userID1"),
			expectedUserID:      "userID1",
			expectedChannelID:   "channelID1",
			expectedJustConnect: false,
		},
		{
			name:        "Legacy state without nonce is rejected",
			state:       predictableOAuthState("userID1", "channelID1", true),
			expectError: true,
		},
		{
			name:        "State with empty nonce is rejected",
			state:       predictableOAuthState("userID1", "channelID1", true) + ".",
			expectError: true,
		},
		{
			name:        "State with short nonce is rejected",
			state:       predictableOAuthState("userID1", "channelID1", true) + ".abc123",
			expectError: true,
		},
		{
			name:        "State with non-hex nonce is rejected",
			state:       predictableOAuthState("userID1", "channelID1", true) + "." + strings.Repeat("z", len(testOAuthStateNonce)),
			expectError: true,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			mockAPI := &plugintest.API{}
			p := SetupMockPlugin(mockAPI, nil, nil)

			if tc.expectError {
				allowAnyLogs(mockAPI)
			}

			key, userID, channelID, justConnect, err := p.ParseState(tc.state)

			if tc.expectError {
				require.Error(t, err)
				if tc.expectedErrMsg != "" {
					require.Equal(t, tc.expectedErrMsg, err.Error())
				}
			} else {
				require.NoError(t, err)
				require.Equal(t, tc.expectedKey, key)
				require.Equal(t, tc.expectedUserID, userID)
				require.Equal(t, tc.expectedChannelID, channelID)
				require.Equal(t, tc.expectedJustConnect, justConnect)
			}
			mockAPI.AssertExpectations(t)
		})
	}
}

func SetupMockPlugin(mockAPI *plugintest.API, mockTracker *MockTracker, mockClient *MockClient) *Plugin {
	return &Plugin{
		MattermostPlugin: plugin.MattermostPlugin{
			API: mockAPI,
		},
		tracker: mockTracker,
	}
}
